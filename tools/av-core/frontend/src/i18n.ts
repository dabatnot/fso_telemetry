export function translate(language: Language, key: TranslationKey, variables: Record<string, string> = {}): string {
  return Object.entries(variables).reduce(
    (message, [name, value]) => message.replaceAll(`{${name}}`, value),
    translations[language][key]
  );
}

export function initialLanguage(): Language {
  const stored = localStorage.getItem("av-core-language");
  if (LANGUAGE_OPTIONS.some((option) => option.code === stored)) return stored as Language;
  const browserLanguage = navigator.language.toLowerCase().split("-")[0];
  return LANGUAGE_OPTIONS.some((option) => option.code === browserLanguage) ? browserLanguage as Language : "en";
}
